#!/usr/bin/env python3
"""Run the benchmark suite and print a markdown results table.

    python3 bench/run.py                    # everything, ~2 minutes
    python3 bench/run.py --quick            # shorter runs, for a sanity check
    python3 bench/run.py --only topic,sse   # a subset
    python3 bench/run.py --out bench/RESULTS.md

Exits non-zero if a budget asserted by an earlier phase is breached. The 1 kHz CPU figure is
reported but never fails: it is dominated by the distro and the middleware rather than by
anything in this package.

Needs a sourced ROS 2 environment, and a zenoh router if the RMW is rmw_zenoh_cpp.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
import time
from collections.abc import Sequence
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(Path(__file__).parent))

import scenarios  # noqa: E402
from harness import hardware  # noqa: E402
from scenarios import Failure, Row  # noqa: E402

SCENARIOS = ("converters", "policy", "topic", "service", "sse", "cpu")


def main(argv: Sequence[str] | None = None) -> int:
    """Run the selected scenarios, write the table, and gate on the asserted budgets."""
    parser = argparse.ArgumentParser(
        prog="bench/run.py",
        description="Benchmark ros2_http_gateway and emit a markdown results table.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=f"scenarios: {', '.join(SCENARIOS)}",
    )
    parser.add_argument("--out", type=Path, help="write the table here as well as to stdout")
    parser.add_argument("--quick", action="store_true", help="shorter runs; numbers are noisier")
    parser.add_argument("--only", help="comma-separated subset of the scenarios")
    args = parser.parse_args(argv)

    selected = SCENARIOS if not args.only else tuple(args.only.split(","))
    unknown = [name for name in selected if name not in SCENARIOS]
    if unknown:
        parser.error(
            f"unknown scenario(s): {', '.join(unknown)}. Choose from {', '.join(SCENARIOS)}"
        )

    seconds = 3.0 if args.quick else 10.0
    samples = 100 if args.quick else 400
    clients = (1, 8) if args.quick else (1, 8, 32)

    rows: list[Row] = []
    failures: list[Failure] = []
    facts = hardware()
    started = time.monotonic()

    with tempfile.TemporaryDirectory(prefix="gateway-bench-") as scratch:
        directory = Path(scratch)
        for name in selected:
            print(f"-- {name}", file=sys.stderr, flush=True)
            produced, broke = _run(name, directory, seconds, samples, clients)
            rows.extend(produced)
            failures.extend(broke)

    table = _render(rows, facts, failures, time.monotonic() - started)
    print(table)
    if args.out:
        args.out.write_text(table, encoding="utf-8")
        print(f"\nwrote {args.out}", file=sys.stderr)

    for failure in failures:
        print(f"REGRESSION {failure.scenario}: {failure.detail}", file=sys.stderr)
    return 1 if failures else 0


def _run(
    name: str, directory: Path, seconds: float, samples: int, clients: tuple[int, ...]
) -> tuple[list[Row], list[Failure]]:
    if name == "converters":
        return scenarios.converters(directory)
    if name == "policy":
        return scenarios.policy_cost(directory)
    if name == "topic":
        rows = list(scenarios.topic_get(directory, seconds=seconds, connections=32))
        rows += list(
            scenarios.topic_get_unauthenticated(directory, seconds=seconds / 2, connections=32)
        )
        return rows, []
    if name == "service":
        return list(scenarios.service_call(directory, samples=samples)), []
    if name == "sse":
        return list(scenarios.sse_fanout(directory, clients=clients, seconds=seconds)), []
    return scenarios.idle_cpu(directory, seconds=seconds)


def _render(rows: list[Row], facts: dict[str, str], failures: list[Failure], took: float) -> str:
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python3 bench/run.py`. Every figure is for the machine below; a load",
        "driver written in Python shares its cores with the gateway, so throughput is a floor",
        "rather than a ceiling.",
        "",
        "| | |",
        "|---|---|",
    ]
    labels = {
        "cpu": "CPU",
        "cores": "Cores",
        "memory": "Memory",
        "kernel": "Kernel",
        "python": "Python",
        "ros_distro": "ROS distro",
        "rmw": "RMW",
        "gateway": "Gateway version",
        "driver": "Load driver",
    }
    lines += [f"| {labels.get(key, key)} | {value} |" for key, value in facts.items()]
    lines += [f"| Wall clock | {took:.0f} s |", ""]

    lines += ["| Scenario | Metric | Value | Budget | |", "|---|---|---|---|---|"]
    previous = ""
    for row in rows:
        scenario = "" if row.scenario == previous else row.scenario
        previous = row.scenario
        lines.append(f"| {scenario} | {row.metric} | {row.value} | {row.budget} | {row.verdict} |")

    lines += ["", "## Budgets", ""]
    if failures:
        lines += [f"**REGRESSION** {failure.scenario}: {failure.detail}" for failure in failures]
    else:
        lines.append("Every asserted budget held.")
    lines += [
        "",
        "The 1 kHz CPU figure is informational. It is dominated by the distro and the RMW: on",
        "Humble rclpy spends most of a core dispatching 900 msg/s before any code here runs,",
        "and rmw_zenoh_cpp costs noticeably more than rmw_fastrtps_cpp on the same machine.",
        "What matters is that it stays close to a do-nothing subscriber on the same pairing.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
